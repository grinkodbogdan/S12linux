#!/usr/bin/env python3
"""Pre-renders fonts into anti-aliased glyph bitmaps, as a C header.

usage: font_gen.py OUT.h NAME:TTF:SIZE...
"""
import sys
from PIL import ImageFont

FIRST, LAST = 32, 126


def gen(name, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = round(font.getlength(ch))
        mask = font.getmask(ch, mode="L")
        w, h = mask.size
        x0, y0, _, _ = font.getbbox(ch)
        glyphs.append((len(data), w, h, x0, y0, adv))
        data += bytes(mask)
    out = ["/* %s %dpx */" % (path.split("/")[-1], size)]
    out.append("static const unsigned char %s_bitmap[%d] = {" % (name, max(len(data), 1)))
    for i in range(0, len(data), 24):
        out.append("\t" + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append("static const Glyph %s_glyphs[%d] = {" % (name, len(glyphs)))
    for g in glyphs:
        out.append("\t{%d, %d, %d, %d, %d, %d}," % g)
    out.append("};")
    out.append("static const FontData %s = {%s_bitmap, %s_glyphs, %d, %d};" % (
        name, name, name, ascent + descent, ascent))
    return "\n".join(out)


def main():
    parts = ["/* Generated by font_gen.py. Do not edit. */",
             "#define FONT_FIRST %d" % FIRST, "#define FONT_LAST %d" % LAST]
    for spec in sys.argv[2:]:
        name, path, size = spec.split(":")
        parts.append(gen(name, path, int(size)))
    open(sys.argv[1], "w").write("\n".join(parts) + "\n")


main()
